#!/usr/bin/env python3
"""Skill template validator (Wave 4+ machine-template B-1).

Implements the §4.2 spec. Validator input = sidecar (`skills/<name>/skill.template.json`)
+ skill directory; outputs pass/fail + missing-fields list.

Always-on checks (per ADR §4.2):
- sidecar schema valid (via _skill_template_schema.check_skill_template)
- SKILL.md frontmatter has exactly name + description (no extras)
- SKILL.md contains a Boundaries-related H2 (loose match: boundary/stop/scope)
- triggers.yaml has ≥5 cases for this skill
- skill name in aqg_doctor.py skill-name tuples
- skill opts into wrapper generation (`wrapper_generated: true` in the sidecar)
- skill name in both install.sh files (source + claude pack)
- exit-code contract (0/1/2/3/70) documented in scripts entry docstring or SKILL.md
- agents/openai.yaml present with non-empty interface.display_name (Codex picker
  fallback guard — missing display_name renders the "Aqg <Name>" slug fallback)

Conditional / advisory:
- audit_mode_required → warn-only (Q6 advisory v1)
- _aqg_context.sh source pattern → warn-only (post PR-3b3 will become required)
- description competing-context / pushiness → warn-only (Anthropic skill-creator;
  flags "always use" / "best skill" / "for all tasks" style universal-priority
  phrasing; GUIDE §2.3b)
- wrapper out of sync with source (managed skills) → warn-only; `--strict` fails
  to match the CI regen→git-status gate (reuses aqg_skill_gen.regen_one check)

CLI:
    python3 scripts/aqg_skill_validator.py <skill-name>
    python3 scripts/aqg_skill_validator.py <skill-name> --strict   # fail on warnings
    python3 scripts/aqg_skill_validator.py <skill-name> --json     # JSON output

Exit codes:
    0: success - no violations; advisory warnings allowed unless --strict
    1: violations found in sidecar / skill_dir / cross_cutting (or under strict)
    2: usage error - sidecar missing, skill dir missing, or repo root not found
    3: config_error - reserved for future use (not currently emitted)
    70: internal_error - reserved for future use (not currently emitted)

Requires PyYAML (a DECLARED dependency) to parse triggers.yaml / openai.yaml /
SKILL.md frontmatter. SKILL.md frontmatter + openai.yaml display_name degrade to
a best-effort regex fallback without it, but the triggers-count check
(_count_triggers_for_skill) hard-fails without PyYAML — install it with
`pip install -r requirements.txt` (declares pyyaml). Otherwise stdlib-only.
"""

