# a3 audit fix #2: explicit allowlist of accepted boundary-section H2 titles.
# Loose-regex (Owner / Scope) was over-permissive AND under-permissive (existing
# closeout skill uses Workflow / Completion Standard / Final Answer Shape).
# We now require an exact match; missing boundary H2 in skills with
# boundary_class != read-only is a hard violation; read-only skills get advisory.
_ACCEPTED_BOUNDARY_H2 = frozenset({
    "## Boundaries",
    "## Boundary Rules",
    "## Stop Boundaries",
    "## Stop Rules",
})

# Source-line pattern for _aqg_context.sh helper (post PR-3b3 advisory)
_AQG_CONTEXT_SOURCE_RE = re.compile(
    r"source\s+\"?\$?\{?[A-Z_]*ROOT[^\"]*?_aqg_context\.sh"
)

# Frontmatter parser: simple YAML key: value (no nested) — frontmatter must be
# delimited by `---` lines and contain only `name:` and `description:` keys.
_FRONTMATTER_KEY_RE = re.compile(r"^([a-zA-Z_][a-zA-Z0-9_-]*)\s*:\s*(.*?)\s*$")


# ===== Repo root resolution =====


def _find_repo_root(start: Path | None = None) -> Path:
    if start is None:
        start = Path(__file__).resolve().parent
    p = start.resolve()
    for _ in range(10):
        if (p / "VERSION").is_file() and (p / "scripts").is_dir() and (p / "templates").is_dir():
            return p
        if p.parent == p:
            break
        p = p.parent
    raise RuntimeError(
        f"cannot find AQG repo root from {start}; expected VERSION + scripts/ + templates/"
    )


